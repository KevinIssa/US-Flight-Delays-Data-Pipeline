-- Question business 1 :
-- Comment evoluent les retards chaque mois, quelles en sont les causes,
-- et quel est le volume de passagers correspondant ?
-- Un vol est considere en retard si ARR_DELAY >= 15 minutes.
-- Le taux exclut les vols annules et les vols sans heure d'arrivee renseignee.
-- Les taux *_PCT_TOTAL utilisent tous les vols comme denominateur.
-- Les passagers sont agreges SEPAREMENT pour eviter de multiplier leurs totaux.

CREATE OR ALTER VIEW dbo.vw_Evolution_Retards_Mensuels
AS
WITH MonthlyFlights AS (
    SELECT
        YEAR(DF.FLIGHT_DATE) AS [YEAR],
        MONTH(DF.FLIGHT_DATE) AS [MONTH],
        COUNT_BIG(*) AS TOTAL_FLIGHTS,
        COUNT_BIG(CASE
            WHEN F.CANCELLED = 0 AND F.ARR_DELAY IS NOT NULL THEN 1
        END) AS FLIGHTS_WITH_ARRIVAL_DATA,
        COUNT_BIG(CASE
            WHEN F.CANCELLED = 0 AND F.ARR_DELAY >= 15 THEN 1
        END) AS DELAYED_FLIGHTS_15MIN,
        AVG(CASE
            WHEN F.CANCELLED = 0 AND F.ARR_DELAY >= 15
            THEN CAST(F.ARR_DELAY AS DECIMAL(18,2))
        END) AS AVG_DELAY_MINUTES,
        COUNT_BIG(CASE WHEN F.CANCELLED = 1 THEN 1 END) AS CANCELLED_FLIGHTS,
        COUNT_BIG(CASE
            WHEN F.CANCELLED = 1 AND F.CANCELLATION_CODE = 'B' THEN 1
        END) AS WEATHER_CANCELLED_FLIGHTS,
        COUNT_BIG(CASE WHEN F.CARRIER_DELAY > 0 THEN 1 END) AS CARRIER_DELAYED_FLIGHTS,
        COUNT_BIG(CASE WHEN F.WEATHER_DELAY > 0 THEN 1 END) AS WEATHER_DELAYED_FLIGHTS,
        COUNT_BIG(CASE WHEN F.NAS_DELAY > 0 THEN 1 END) AS NAS_DELAYED_FLIGHTS,
        COUNT_BIG(CASE WHEN F.SECURITY_DELAY > 0 THEN 1 END) AS SECURITY_DELAYED_FLIGHTS,
        COUNT_BIG(CASE WHEN F.LATE_AIRCRAFT_DELAY > 0 THEN 1 END) AS LATE_AIRCRAFT_DELAYED_FLIGHTS,
        SUM(CAST(CASE WHEN F.CARRIER_DELAY > 0 THEN F.CARRIER_DELAY ELSE 0 END AS DECIMAL(19,2))) AS CARRIER_DELAY_MINUTES,
        SUM(CAST(CASE WHEN F.WEATHER_DELAY > 0 THEN F.WEATHER_DELAY ELSE 0 END AS DECIMAL(19,2))) AS WEATHER_DELAY_MINUTES,
        SUM(CAST(CASE WHEN F.NAS_DELAY > 0 THEN F.NAS_DELAY ELSE 0 END AS DECIMAL(19,2))) AS NAS_DELAY_MINUTES,
        SUM(CAST(CASE WHEN F.SECURITY_DELAY > 0 THEN F.SECURITY_DELAY ELSE 0 END AS DECIMAL(19,2))) AS SECURITY_DELAY_MINUTES,
        SUM(CAST(CASE WHEN F.LATE_AIRCRAFT_DELAY > 0 THEN F.LATE_AIRCRAFT_DELAY ELSE 0 END AS DECIMAL(19,2))) AS LATE_AIRCRAFT_DELAY_MINUTES
    FROM dbo.Fact_Flights AS F
    INNER JOIN dbo.Dim_Date_Flights AS DF
        ON DF.DATE_ID = F.DATE_ID
    GROUP BY
        YEAR(DF.FLIGHT_DATE),
        MONTH(DF.FLIGHT_DATE)
),
MonthlyPassengers AS (
    SELECT
        DP.[YEAR],
        DP.[MONTH],
        SUM(CAST(FP.PASSENGERS AS BIGINT)) AS TOTAL_PASSENGERS,
        COUNT_BIG(*) AS TOTAL_PASSENGER_SEGMENTS
    FROM dbo.Fact_Passengers AS FP
    INNER JOIN dbo.Dim_Date_Passengers AS DP
        ON DP.DATE_ID = FP.DATE_ID
    GROUP BY
        DP.[YEAR],
        DP.[MONTH]
)
SELECT
    F.[YEAR],
    F.[MONTH],
    DATEFROMPARTS(F.[YEAR], F.[MONTH], 1) AS MONTH_DATE,
    F.TOTAL_FLIGHTS,
    F.FLIGHTS_WITH_ARRIVAL_DATA,
    F.DELAYED_FLIGHTS_15MIN,
    CAST(
        F.DELAYED_FLIGHTS_15MIN * 100.0
        / NULLIF(F.FLIGHTS_WITH_ARRIVAL_DATA, 0)
        AS DECIMAL(6,2)
    ) AS DELAY_RATE_PCT,
    -- Pourcentages sur TOUS les vols, y compris les vols annules.
    CAST(
        F.DELAYED_FLIGHTS_15MIN * 100.0
        / NULLIF(F.TOTAL_FLIGHTS, 0)
        AS DECIMAL(6,2)
    ) AS DELAYED_FLIGHTS_PCT_TOTAL,
    CAST(
        F.CANCELLED_FLIGHTS * 100.0
        / NULLIF(F.TOTAL_FLIGHTS, 0)
        AS DECIMAL(6,2)
    ) AS CANCELLED_FLIGHTS_PCT_TOTAL,
    CAST(F.AVG_DELAY_MINUTES AS DECIMAL(12,2)) AS AVG_DELAY_MINUTES,
    F.CANCELLED_FLIGHTS,
    F.WEATHER_CANCELLED_FLIGHTS,
    P.TOTAL_PASSENGERS,
    P.TOTAL_PASSENGER_SEGMENTS,
    F.CARRIER_DELAYED_FLIGHTS,
    F.WEATHER_DELAYED_FLIGHTS,
    F.NAS_DELAYED_FLIGHTS,
    F.SECURITY_DELAYED_FLIGHTS,
    F.LATE_AIRCRAFT_DELAYED_FLIGHTS,
    F.CARRIER_DELAY_MINUTES,
    F.WEATHER_DELAY_MINUTES,
    F.NAS_DELAY_MINUTES,
    F.SECURITY_DELAY_MINUTES,
    F.LATE_AIRCRAFT_DELAY_MINUTES
FROM MonthlyFlights AS F
LEFT JOIN MonthlyPassengers AS P
    ON P.[YEAR] = F.[YEAR]
   AND P.[MONTH] = F.[MONTH];
GO

