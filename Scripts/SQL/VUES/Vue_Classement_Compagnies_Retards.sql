-- Question business 2 :
-- Quelles compagnies ont le plus de retards, en taux et en nombre ?
-- Classement sur l'ensemble de la periode presente dans Fact_Flights.
-- Un vol est considere en retard si ARR_DELAY >= 15 minutes.
-- Les causes peuvent se cumuler pour un meme vol.
-- Les taux *_PCT_TOTAL utilisent tous les vols comme denominateur.

CREATE OR ALTER VIEW dbo.vw_Classement_Compagnies_Retards
AS
WITH AirlineFlights AS (
    SELECT
        F.REPORTING_AIRLINE_ID AS DOT_ID_REPORTING_AIRLINE,
        COUNT_BIG(*) AS TOTAL_FLIGHTS,
        COUNT_BIG(CASE
            WHEN F.CANCELLED = 0 AND F.ARR_DELAY IS NOT NULL THEN 1
        END) AS FLIGHTS_WITH_ARRIVAL_DATA,
        COUNT_BIG(CASE
            WHEN F.CANCELLED = 0 AND F.ARR_DELAY >= 15 THEN 1
        END) AS DELAYED_FLIGHTS_15MIN,
        AVG(CASE
            WHEN F.CANCELLED = 0 AND F.ARR_DELAY >= 15
            THEN CAST(F.ARR_DELAY AS DECIMAL(18,2))
        END) AS AVG_DELAY_MINUTES,
        COUNT_BIG(CASE WHEN F.CANCELLED = 1 THEN 1 END) AS CANCELLED_FLIGHTS,
        COUNT_BIG(CASE
            WHEN F.CANCELLED = 1 AND F.CANCELLATION_CODE = 'B' THEN 1
        END) AS WEATHER_CANCELLED_FLIGHTS,
        COUNT_BIG(CASE WHEN F.CARRIER_DELAY > 0 THEN 1 END) AS CARRIER_DELAYED_FLIGHTS,
        COUNT_BIG(CASE WHEN F.WEATHER_DELAY > 0 THEN 1 END) AS WEATHER_DELAYED_FLIGHTS,
        COUNT_BIG(CASE WHEN F.NAS_DELAY > 0 THEN 1 END) AS NAS_DELAYED_FLIGHTS,
        COUNT_BIG(CASE WHEN F.SECURITY_DELAY > 0 THEN 1 END) AS SECURITY_DELAYED_FLIGHTS,
        COUNT_BIG(CASE WHEN F.LATE_AIRCRAFT_DELAY > 0 THEN 1 END) AS LATE_AIRCRAFT_DELAYED_FLIGHTS,
        SUM(CAST(CASE WHEN F.CARRIER_DELAY > 0 THEN F.CARRIER_DELAY ELSE 0 END AS DECIMAL(19,2))) AS CARRIER_DELAY_MINUTES,
        SUM(CAST(CASE WHEN F.WEATHER_DELAY > 0 THEN F.WEATHER_DELAY ELSE 0 END AS DECIMAL(19,2))) AS WEATHER_DELAY_MINUTES,
        SUM(CAST(CASE WHEN F.NAS_DELAY > 0 THEN F.NAS_DELAY ELSE 0 END AS DECIMAL(19,2))) AS NAS_DELAY_MINUTES,
        SUM(CAST(CASE WHEN F.SECURITY_DELAY > 0 THEN F.SECURITY_DELAY ELSE 0 END AS DECIMAL(19,2))) AS SECURITY_DELAY_MINUTES,
        SUM(CAST(CASE WHEN F.LATE_AIRCRAFT_DELAY > 0 THEN F.LATE_AIRCRAFT_DELAY ELSE 0 END AS DECIMAL(19,2))) AS LATE_AIRCRAFT_DELAY_MINUTES
    FROM dbo.Fact_Flights AS F
    GROUP BY
        F.REPORTING_AIRLINE_ID
),
AirlineRates AS (
    SELECT
        A.*,
        CAST(
            A.DELAYED_FLIGHTS_15MIN * 100.0
            / NULLIF(A.FLIGHTS_WITH_ARRIVAL_DATA, 0)
            AS DECIMAL(6,2)
        ) AS DELAY_RATE_PCT
    FROM AirlineFlights AS A
)
SELECT
    DENSE_RANK() OVER (
        ORDER BY R.DELAY_RATE_PCT DESC
    ) AS RANK_BY_DELAY_RATE,
    DENSE_RANK() OVER (
        ORDER BY R.DELAYED_FLIGHTS_15MIN DESC
    ) AS RANK_BY_DELAYED_FLIGHTS,
    R.DOT_ID_REPORTING_AIRLINE,
    AL.REPORTING_AIRLINE,
    AL.AIRLINE_NAME,
    R.TOTAL_FLIGHTS,
    R.FLIGHTS_WITH_ARRIVAL_DATA,
    R.DELAYED_FLIGHTS_15MIN,
    R.DELAY_RATE_PCT,
    -- Pourcentages sur TOUS les vols, y compris les vols annules.
    CAST(
        R.DELAYED_FLIGHTS_15MIN * 100.0
        / NULLIF(R.TOTAL_FLIGHTS, 0)
        AS DECIMAL(6,2)
    ) AS DELAYED_FLIGHTS_PCT_TOTAL,
    CAST(
        R.CANCELLED_FLIGHTS * 100.0
        / NULLIF(R.TOTAL_FLIGHTS, 0)
        AS DECIMAL(6,2)
    ) AS CANCELLED_FLIGHTS_PCT_TOTAL,
    CAST(R.AVG_DELAY_MINUTES AS DECIMAL(12,2)) AS AVG_DELAY_MINUTES,
    R.CANCELLED_FLIGHTS,
    R.WEATHER_CANCELLED_FLIGHTS,
    R.CARRIER_DELAYED_FLIGHTS,
    R.WEATHER_DELAYED_FLIGHTS,
    R.NAS_DELAYED_FLIGHTS,
    R.SECURITY_DELAYED_FLIGHTS,
    R.LATE_AIRCRAFT_DELAYED_FLIGHTS,
    R.CARRIER_DELAY_MINUTES,
    R.WEATHER_DELAY_MINUTES,
    R.NAS_DELAY_MINUTES,
    R.SECURITY_DELAY_MINUTES,
    R.LATE_AIRCRAFT_DELAY_MINUTES
FROM AirlineRates AS R
INNER JOIN dbo.Dim_Airline AS AL
    ON AL.DOT_ID_REPORTING_AIRLINE = R.DOT_ID_REPORTING_AIRLINE;
GO

