CREATE OR ALTER VIEW dbo.Airline_Delay_Rate_Ranking_View
AS

WITH Airline_Delays AS (
    SELECT
        F.REPORTING_AIRLINE_ID,

        COUNT_BIG(*) AS TOTAL_OPERATED_FLIGHTS,

        COUNT_BIG(CASE
            WHEN F.ARR_DELAY >= 15 THEN 1
        END) AS DELAYED_FLIGHTS

    FROM dbo.Fact_Flights AS F

    WHERE F.CANCELLED = 0

    GROUP BY F.REPORTING_AIRLINE_ID
),

Airline_Rates AS (
    SELECT
        REPORTING_AIRLINE_ID,
        TOTAL_OPERATED_FLIGHTS,
        DELAYED_FLIGHTS,

        DELAYED_FLIGHTS * 100.0
            / NULLIF(TOTAL_OPERATED_FLIGHTS, 0) AS DELAY_RATE

    FROM Airline_Delays
)

SELECT
    DENSE_RANK() OVER (
        ORDER BY AR.DELAY_RATE DESC
    ) AS DELAY_RANK,

    AL.AIRLINE_NAME,
    AR.TOTAL_OPERATED_FLIGHTS,
    AR.DELAYED_FLIGHTS,

    CAST(AR.DELAY_RATE AS DECIMAL(6,2)) AS DELAY_RATE_PCT

FROM Airline_Rates AS AR

INNER JOIN dbo.Dim_Airline AS AL
    ON AL.DOT_ID_REPORTING_AIRLINE = AR.REPORTING_AIRLINE_ID;
GO

-- Checking
SELECT *
FROM dbo.Airline_Delay_Rate_Ranking_View
ORDER BY DELAY_RATE_PCT DESC;
